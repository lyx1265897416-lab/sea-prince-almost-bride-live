        if k == 'seg2' and sp[k] and str(sp[k][-1][2]).startswith(('双人近景', '双人中近景', '近景')): sp[k][-1][2] = '双人中景，固定'  # V2.4：吻戏也一样（回归：末帧是贴脸近景时，回正把坐着改成站着、把开衫画丢）  # V2.3：末帧只拍到胸口，下一轮第 1 段要自己猜下半身（牛仔裤变成黑裤、她变成牛仔短裤），收尾看得到全身穿着
